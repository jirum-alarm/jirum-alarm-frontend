/**
 * 실험 배정 버킷 0~99 — crawling-server `src/experiment/experiment-bucket.ts` 와 **같은 값**을 낸다.
 * sha256(`${experimentId}:${unitId}`) 앞 4바이트(big-endian) % 100.
 *
 * 분석은 서버 user_history 의 deviceId 로 같은 값을 다시 계산한다 — 배정 이벤트를 따로 남기지 않는다.
 * 그래서 앱이 클라에서 정하는 실험도 해시는 반드시 이 함수(=서버 함수)여야 한다.
 * ★진행 중인 실험의 id 를 바꾸면 배정이 통째로 섞인다.
 *
 * sha256 을 직접 둔 이유: 앱엔 crypto.subtle 이 없고 expo-crypto 는 네이티브 모듈(스토어 빌드)이다.
 */
export function experimentBucket(unitId: string, experimentId: string): number {
  const digest = sha256(utf8(`${experimentId}:${unitId}`));
  const head =
    ((digest[0] << 24) | (digest[1] << 16) | (digest[2] << 8) | digest[3]) >>>
    0;
  return head % 100;
}

/** UTF-8 바이트. TextEncoder 는 런타임(Hermes 버전)마다 있는지 장담 못 해 직접 만든다. */
function utf8(text: string): Uint8Array {
  const bytes: number[] = [];
  for (const char of text) {
    const cp = char.codePointAt(0)!;
    if (cp < 0x80) bytes.push(cp);
    else if (cp < 0x800) bytes.push(0xc0 | (cp >> 6), 0x80 | (cp & 0x3f));
    else if (cp < 0x10000)
      bytes.push(
        0xe0 | (cp >> 12),
        0x80 | ((cp >> 6) & 0x3f),
        0x80 | (cp & 0x3f),
      );
    else
      bytes.push(
        0xf0 | (cp >> 18),
        0x80 | ((cp >> 12) & 0x3f),
        0x80 | ((cp >> 6) & 0x3f),
        0x80 | (cp & 0x3f),
      );
  }
  return Uint8Array.from(bytes);
}

